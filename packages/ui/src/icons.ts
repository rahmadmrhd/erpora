export type IconName = keyof typeof iconRegistry;

const warned = new Set<string>();

/**
 * Menemukan komponen ikon menurut nama. Nama kosong, asing, atau nama prototipe Object (`constructor`) menghasilkan
 * `undefined`; di development nama asing dicatat sekali lewat `console.warn`.
 */
export function resolveIcon(name?: string): ComponentType<{ className?: string }> | undefined {
  if (!name) return undefined;
  if (Object.hasOwn(iconRegistry, name)) return iconRegistry[name as IconName];
  if (!warned.has(name) && process.env.NODE_ENV !== "production") {
    warned.add(name);
    console.warn(`@erpora/ui: ikon "${name}" tidak terdaftar di iconRegistry`);
  }
  return undefined;
}
