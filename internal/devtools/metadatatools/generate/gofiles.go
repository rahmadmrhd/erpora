// GeneratedHeader adalah kepala wajib semua berkas bangkitan Go dan TypeScript (design D-14). Hilangnya baris
// ini menandai berkas diubah tangan atau bukan milik generator.
const GeneratedHeader = "// Code generated by erpora metadata:generate. DO NOT EDIT."

var goTmpl = func() map[string]*template.Template {
	out := map[string]*template.Template{}
	for _, name := range []string{resource.DomainMetaTemplate, resource.HTTPDTOTemplate} {
		src, err := resource.FS.ReadFile(name)
		if err != nil {
			panic("templat resource tidak ada: " + name) // embed: kesalahan pemrograman, bukan masukan
		}
		out[name] = template.Must(template.New(name).Delims("<%", "%>").Option("missingkey=error").Parse(string(src)))
	}
	return out
}()

func renderTemplate(name string, data any) ([]byte, error) {
	var buf bytes.Buffer
	if err := goTmpl[name].Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("render %s: %w", name, err)
	}
	return buf.Bytes(), nil
}

type namedLiteral struct{ Name, Value string }

type domainData struct {
	Header, Pkg, Pascal, KeyLiteral, LabelTemplate string
	UsesJSON                                       bool
	FieldConsts, EnumConsts                        []namedLiteral
	Fields, Rules                                  []string
	LockWhen                                       string
	Lifecycle                                      string
	Axes                                           []string
}

type dtoField struct {
	GoName, GoType, Tag, NameLiteral string
}

type dtoData struct {
	Header, Pkg, Pascal, DomainImport string
	Writable                          []dtoField
	Pairs                             []dtoPair
}

// dtoPair adalah pasangan rename untuk FillRenamePairs: nama field Go dan literal nama JSON.
type dtoPair struct {
	NewGo, OldGo, NewLit, OldLit string
}

var goTypeOf = map[string]string{
	"string": "string", "text": "string", "enum": "string", "uuid": "string", "date": "string",
	"datetime": "string", "decimal": "string", "integer": "int64", "boolean": "bool",
}

// jsonTag menyusun tag struct dari nama field yang sudah tervalidasi sebagai identifier (tanpa kutip, backtick,
// atau spasi); gagal tertutup bila nama mengandungnya.
func jsonTag(name string) (string, error) {
	if strings.ContainsAny(name, "`\"\\ \t\r\n,") || name == "" || name == "-" {
		return "", inputErr("nama field %q tidak dapat menjadi tag JSON", name)
	}
	return "`json:" + strconv.Quote(name) + "`", nil
}

// renderDomain membangkitkan <nama>_meta.gen.go (domain tanpa I/O).
func renderDomain(m *resModel, pkg string) ([]byte, error) {
	e := &emitter{}
	d := domainData{Header: GeneratedHeader, Pkg: pkg, Pascal: m.Pascal, KeyLiteral: goString(m.Res.Key)}
	if m.LabelTpl != "" {
		d.LabelTemplate = goString(m.LabelTpl)
	}
	idents := map[string]string{m.Pascal + "Key": "kunci resource", m.Pascal + "LabelTemplate": "templat label", m.Pascal + "Spec": "spesifikasi"}
	claim := func(id, what string) error {
		if prev, dup := idents[id]; dup {
			return inputErr("resource %s: identifier Go %s (%s) bertabrakan dengan %s", m.Res.Key, id, what, prev)
		}
		idents[id] = what
		return nil
	}
	for _, f := range m.Fields {
		fn := m.Pascal + "Field" + f.GoName
		if err := claim(fn, "field "+f.Name); err != nil {
			return nil, err
		}
		d.FieldConsts = append(d.FieldConsts, namedLiteral{fn, goString(f.Name)})
		lit, err := e.fieldSpec(f)
		if err != nil {
			return nil, err
		}
		d.Fields = append(d.Fields, lit)
		for _, v := range f.Enum {
			pv := pascalValue(v)
			if pv == "" {
				continue
			}
			cn := m.Pascal + f.GoName + pv
			if err := claim(cn, "enum "+f.Name); err != nil {
				return nil, err
			}
			d.EnumConsts = append(d.EnumConsts, namedLiteral{cn, goString(v)})
		}
	}
	for _, r := range m.Rules {
		lit, err := e.ruleSpec(r)
		if err != nil {
			return nil, err
		}
		d.Rules = append(d.Rules, lit)
	}
	if m.LockWhen != nil {
		s, err := e.cond(m.LockWhen)
		if err != nil {
			return nil, fmt.Errorf("lockWhen: %w", err)
		}
		d.LockWhen = s
	}
	if m.Lifecycle != nil {
		d.Lifecycle = statusSpec(m.Lifecycle)
	}
	for _, ax := range m.Axes {
		d.Axes = append(d.Axes, statusSpec(ax))
	}
	d.UsesJSON = e.usesJSON
	raw, err := renderTemplate(resource.DomainMetaTemplate, d)
	if err != nil {
		return nil, err
	}
	return formatGo(m.Snake+"_meta.gen.go", raw)
}

// renderDTO membangkitkan <nama>_dto.gen.go (presentation/http).
func renderDTO(m *resModel, pkg, domainImport string) ([]byte, error) {
	if !importPathRe.MatchString(domainImport) {
		return nil, inputErr("path import domain %q tidak sah", domainImport)
	}
	// Impor domain adalah literal terkutip (goString), bukan teks mentah dari go.mod.
	d := dtoData{Header: GeneratedHeader, Pkg: pkg, Pascal: m.Pascal, DomainImport: goString(domainImport)}
	for _, f := range m.writable() {
		gt, ok := goTypeOf[f.Type]
		if !ok {
			return nil, inputErr("field %s: tipe %q tidak punya tipe Go", f.Name, f.Type)
		}
		tag, err := jsonTag(f.Name)
		if err != nil {
			return nil, err
		}
		d.Writable = append(d.Writable, dtoField{GoName: f.GoName, GoType: gt, Tag: tag, NameLiteral: goString(f.Name)})
	}
	for _, p := range m.Pairs {
		d.Pairs = append(d.Pairs, dtoPair{NewGo: p.New.GoName, OldGo: p.Old.GoName, NewLit: goString(p.New.Name), OldLit: goString(p.Old.Name)})
	}
	raw, err := renderTemplate(resource.HTTPDTOTemplate, d)
	if err != nil {
		return nil, err
	}
	return formatGo(m.Snake+"_dto.gen.go", raw)
}

// formatGo memformat keluaran dan sekaligus membuktikan bahwa hasilnya Go yang sah (gagal tertutup bila tidak).
func formatGo(name string, src []byte) ([]byte, error) {
	out, err := gen.FormatGo(name, src)
	if err != nil {
		return nil, fmt.Errorf("%w: keluaran %s bukan Go yang sah: %v", ErrInput, name, err)
	}
	return out, nil
}

// runtimeSource menyalin sumber runtime dengan klausa package diganti dan kepala bangkitan ditambahkan.
func runtimeSource(srcName, fromPkg, toPkg string) ([]byte, error) {
	src, err := resource.FS.ReadFile(srcName)
	if err != nil {
		return nil, fmt.Errorf("sumber runtime %s: %w", srcName, err)
	}
	clause := "\npackage " + fromPkg + "\n"
	text := string(src)
	if strings.Count(text, clause) != 1 {
		return nil, fmt.Errorf("sumber runtime %s: klausa package %s harus tepat satu", srcName, fromPkg)
	}
	text = strings.Replace(text, clause, "\npackage "+toPkg+"\n", 1)
	return gen.FormatGo(srcName, []byte(GeneratedHeader+"\n\n"+text))
}

// goFileStem memastikan nama berkas Go aman dan konsisten (snake_case hasil konversi).
func goFileStem(m *resModel) (string, error) {
	if _, err := naming.ToSnake(m.Name); err != nil {
		return "", inputErr("%v", err)
	}
	return m.Snake, nil
}
