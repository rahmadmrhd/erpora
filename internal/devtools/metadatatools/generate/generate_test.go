func TestOrphansReportedAndRemoved(t *testing.T) {
	root, cat := fixtureRepo(t)
	if _, err := runGen(t, root, Options{}, cat); err != nil {
		t.Fatal(err)
	}
	orphan := "modules/fixturesales/internal/domain/gone_meta.gen.go"
	writeFile(t, root, orphan, generatedHeader+"\n\npackage domain\n")
	res, err := runGen(t, root, Options{Check: true}, cat)
	if !errors.Is(err, ErrDrift) || len(res.Stale) != 1 || res.Stale[0] != orphan {
		t.Fatalf("err=%v stale=%v", err, res.Stale)
	}
	res, err = runGen(t, root, Options{}, cat)
	if err != nil || len(res.Removed) != 1 || res.Removed[0] != orphan {
		t.Fatalf("err=%v removed=%v", err, res.Removed)
	}
	if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(orphan))); !os.IsNotExist(err) {
		t.Error("yatim harus terhapus")
	}
	// Berkas bernama sama tanpa kepala bukan milik generator: tidak disentuh.
	writeFile(t, root, "modules/fixturesales/internal/domain/mine_meta.gen.go", "package domain\n")
	if res, err = runGen(t, root, Options{}, cat); err != nil || len(res.Removed) != 0 {
		t.Fatalf("err=%v removed=%v", err, res.Removed)
	}
}

