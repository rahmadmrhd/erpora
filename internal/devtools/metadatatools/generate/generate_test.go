// TestWorkspaceMatchesCatalogPath membuktikan jalur produksi (check.LoadWorkspace dan check.Run) menghasilkan
// keluaran identik dengan jalur katalog untuk modul fixture, dan gagal tanpa menulis bila check bergalat.
func TestWorkspaceMatchesCatalogPath(t *testing.T) {
	root, cat := fixtureRepo(t)
	want, err := Generate(root, cat, Options{Checker: okChecker{}, Check: true})
	if !errors.Is(err, ErrDrift) {
		t.Fatal(err)
	}
	got, err := GenerateWorkspace(root, Options{Check: true})
	if !errors.Is(err, ErrDrift) {
		t.Fatalf("err = %v problems = %v", err, got.Problems)
	}
	if len(got.Files) != len(want.Files) {
		t.Fatalf("jumlah keluaran %d != %d", len(got.Files), len(want.Files))
	}
	for i := range want.Files {
		if got.Files[i].Path != want.Files[i].Path || string(got.Files[i].Content) != string(want.Files[i].Content) {
			t.Errorf("keluaran %s berbeda antara jalur workspace dan katalog", want.Files[i].Path)
		}
	}
	if _, err := GenerateWorkspace(root, Options{}); err != nil {
		t.Fatal(err)
	}
	if _, err := GenerateWorkspace(root, Options{Check: true}); err != nil {
		t.Fatalf("setelah tulis check harus bersih: %v", err)
	}
}

