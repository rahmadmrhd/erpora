const generatedHeader = "// Code generated by erpora metadata:generate. DO NOT EDIT."

func runGen(t *testing.T, root string, opts Options, cat *resolve.Catalog) (Result, error) {
	t.Helper()
	if opts.Checker == nil {
		opts.Checker = okChecker{}
	}
	return Generate(root, cat, opts)
}

