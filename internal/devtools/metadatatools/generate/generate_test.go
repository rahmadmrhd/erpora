func TestFixtureOutputShape(t *testing.T) {
	root, cat := fixtureRepo(t)
	res, _ := runGen(t, root, Options{Check: true}, cat)
	paths := map[string]bool{}
	for _, p := range filePaths(res) {
		paths[p] = true
	}
	for _, want := range []string{
		"modules/fixturesales/internal/domain/invoice_meta.gen.go",
		"modules/fixturesales/internal/domain/invoice_line_meta.gen.go",
		"modules/fixturesales/internal/domain/meta_runtime.gen.go",
		"modules/fixturesales/internal/presentation/http/invoice_dto.gen.go",
		"modules/fixturesales/internal/presentation/http/invoice_line_dto.gen.go",
		"modules/fixturesales/internal/presentation/http/meta_runtime.gen.go",
		"modules/fixturesales/openapi.yaml",
		"modules/fixturecore/internal/domain/customer_meta.gen.go",
		"modules/fixturecore/openapi.yaml",
	} {
		if !paths[want] {
			t.Errorf("keluaran %s tidak ada", want)
		}
	}
	for _, f := range res.Files {
		if strings.HasSuffix(f.Path, ".ts") {
			t.Errorf("modul fixture tanpa web/ tidak boleh menghasilkan TS: %s", f.Path)
		}
		if !strings.HasPrefix(f.Path, "modules/fixturecore/") && !strings.HasPrefix(f.Path, "modules/fixturesales/") {
			t.Errorf("keluaran di luar direktori modul: %s", f.Path)
		}
		if strings.HasSuffix(f.Path, ".gen.go") && !strings.HasPrefix(string(f.Content), generatedHeader+"\n") {
			t.Errorf("%s: kepala Code generated hilang", f.Path)
		}
		if strings.Contains(string(f.Content), "\r") {
			t.Errorf("%s: harus LF", f.Path)
		}
	}
}

func TestDeterministic(t *testing.T) {
	root, cat := fixtureRepo(t)
	a, _ := runGen(t, root, Options{Check: true}, cat)
	b, _ := runGen(t, root, Options{Check: true}, cat)
	if len(a.Files) != len(b.Files) {
		t.Fatal("jumlah keluaran berbeda")
	}
	for i := range a.Files {
		if a.Files[i].Path != b.Files[i].Path || string(a.Files[i].Content) != string(b.Files[i].Content) {
			t.Errorf("keluaran %s tidak deterministik", a.Files[i].Path)
		}
		if i > 0 && a.Files[i-1].Path >= a.Files[i].Path {
			t.Errorf("urutan tidak terurut: %s sebelum %s", a.Files[i-1].Path, a.Files[i].Path)
		}
	}
}

